"""Drives the real, running AI Government Benefits Navigator app in a real
browser and records the session as video, paced to match the narration
audio durations in audio/manifest.json (generated by synthesize_narration.ps1).

Usage:
    .venv\\Scripts\\python.exe record_demo.py
"""
from __future__ import annotations

import json
import os
import time

from playwright.sync_api import sync_playwright, Page

BASE_URL = "http://localhost:8080"
HERE = os.path.dirname(os.path.abspath(__file__))
MANIFEST_PATH = os.path.join(HERE, "audio", "manifest.json")
VIDEO_DIR = os.path.join(HERE, "raw_video")
VIEWPORT = {"width": 1280, "height": 720}


def load_durations() -> dict[str, float]:
    with open(MANIFEST_PATH, "r", encoding="utf-8-sig") as f:
        manifest = json.load(f)
    return {item["id"]: item["duration"] for item in manifest}


def hold(page: Page, seconds: float):
    if seconds > 0:
        page.wait_for_timeout(seconds * 1000)


def run():
    durations = load_durations()
    os.makedirs(VIDEO_DIR, exist_ok=True)
    for f in os.listdir(VIDEO_DIR):
        os.remove(os.path.join(VIDEO_DIR, f))

    with sync_playwright() as p:
        browser = p.chromium.launch()
        context = browser.new_context(
            viewport=VIEWPORT,
            record_video_dir=VIDEO_DIR,
            record_video_size=VIEWPORT,
        )
        page = context.new_page()

        # ---- Scene 01: intro / landing page ----
        t0 = time.time()
        page.goto(BASE_URL, wait_until="networkidle")
        page.wait_for_selector("text=Find Government Benefits You May Be Eligible For")
        hold(page, durations["01_intro"] - (time.time() - t0))

        # ---- Scene 02: categories ----
        t0 = time.time()
        page.get_by_text("Browse by category").scroll_into_view_if_needed()
        for label in ["Education", "Agriculture", "Healthcare", "Housing"]:
            try:
                page.get_by_text(label, exact=True).first.hover(timeout=1500)
                page.wait_for_timeout(400)
            except Exception:
                pass
        hold(page, durations["02_categories"] - (time.time() - t0))

        # ---- Scene 03: go to chat ----
        t0 = time.time()
        page.get_by_role("link", name="💬 Ask a Question").click()
        page.wait_for_selector('input[aria-label="Type your question"]')
        hold(page, durations["03_goto_chat"] - (time.time() - t0))

        # ---- Scene 04: type the student scenario message ----
        t0 = time.time()
        message = (
            "I am a 20 year old engineering student from Tamil Nadu. My family "
            "income is around 1.5 lakh per year. What scholarships can I apply for?"
        )
        chat_input = page.locator('input[aria-label="Type your question"]')
        chat_input.click()
        chat_input.type(message, delay=70)
        hold(page, durations["04_type_message"] - (time.time() - t0))

        # ---- Scene 05: send + profile extraction ----
        t0 = time.time()
        page.get_by_role("button", name="Send").click()
        try:
            page.wait_for_selector("text=Why this scheme?", timeout=15000)
        except Exception:
            pass
        hold(page, durations["05_extraction"] - (time.time() - t0))

        # ---- Scene 06: matching / recommendations appear ----
        t0 = time.time()
        try:
            page.locator("article").first.scroll_into_view_if_needed()
        except Exception:
            pass
        hold(page, durations["06_matching"] - (time.time() - t0))

        # ---- Scene 07: why this scheme ----
        t0 = time.time()
        try:
            page.get_by_role("button", name="Why this scheme? / What am I missing?").first.click()
        except Exception:
            pass
        hold(page, durations["07_why"] - (time.time() - t0))

        # ---- Scene 08: documents needed ----
        t0 = time.time()
        try:
            page.get_by_role("button", name="Documents needed").first.click()
        except Exception:
            pass
        hold(page, durations["08_documents"] - (time.time() - t0))

        # ---- Scene 09: view details ----
        t0 = time.time()
        try:
            page.get_by_role("link", name="View Details").first.click()
            page.wait_for_selector("text=How to apply", timeout=10000)
        except Exception:
            pass
        hold(page, durations["09_details"] - (time.time() - t0))

        # ---- Scene 10: source card ----
        t0 = time.time()
        try:
            page.get_by_text("Open official government source").scroll_into_view_if_needed()
        except Exception:
            pass
        hold(page, durations["10_source"] - (time.time() - t0))

        # ---- Scene 11: guided profile ----
        t0 = time.time()
        try:
            page.get_by_role("link", name="My Profile").click()
            page.wait_for_selector("text=Tell us about yourself")
            page.locator('input[type="number"]').first.fill("45")
            page.locator("select").nth(1).select_option(label="Tamil Nadu")
            page.get_by_placeholder("e.g. farmer, student, shop owner").fill("farmer")
            page.get_by_role("button", name="Find My Benefits").click()
            page.wait_for_url("**/benefits", timeout=10000)
        except Exception:
            pass
        hold(page, durations["11_profile"] - (time.time() - t0))

        # ---- Scene 12: benefits dashboard ----
        t0 = time.time()
        try:
            page.get_by_text("My Benefits").first.scroll_into_view_if_needed()
        except Exception:
            pass
        hold(page, durations["12_benefits"] - (time.time() - t0))

        # ---- Scene 13: outro ----
        t0 = time.time()
        try:
            page.goto(BASE_URL, wait_until="networkidle")
            page.get_by_text("Why trust this tool?").scroll_into_view_if_needed()
        except Exception:
            pass
        hold(page, durations["13_outro"] - (time.time() - t0))

        context.close()
        browser.close()

    # Playwright names the video file automatically; find it and rename it predictably.
    files = [f for f in os.listdir(VIDEO_DIR) if f.endswith(".webm")]
    if files:
        src = os.path.join(VIDEO_DIR, files[0])
        dst = os.path.join(VIDEO_DIR, "recording.webm")
        os.replace(src, dst)
        print(f"Recording saved to {dst}")
    else:
        print("WARNING: no video file produced.")


if __name__ == "__main__":
    run()
